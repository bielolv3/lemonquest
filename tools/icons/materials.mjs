const names = Object.keys(ICONS);
const COLS = 8, rows = Math.ceil(names.length / COLS);
const atlas = new PNG({ width: COLS * 16, height: rows * 16 });
const meta = { frameWidth: 16, frameHeight: 16, columns: COLS, count: names.length, frames: {} };
names.forEach((n, i) => {
  const m = ICONS[n];
  if (m.length !== 16) throw new Error(`${n}: ${m.length} linhas`);
  m.forEach((row, y) => {
    if (row.length !== 16) console.warn(`aviso: ${n} linha ${y} tem ${row.length}`);
    [...row.padEnd(16, ".").slice(0, 16)].forEach((ch, x) => {
      if (ch === ".") return;
      const c = PAL[ch]; if (!c) throw new Error(`${n}: cor '${ch}'`);
      atlas.data.set(hex(c), ((Math.floor(i / COLS) * 16 + y) * atlas.width + (i % COLS) * 16 + x) * 4);
    });
  });
  meta.frames[n] = i;
});
const S = 6, W = atlas.width * S, H = atlas.height * S;
const prev = new PNG({ width: W, height: H });
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  const ax = (x / S) | 0, ay = (y / S) | 0, i = (ay * atlas.width + ax) * 4, edge = x % (16 * S) === 0 || y % (16 * S) === 0;
  const bg = (((ax >> 1) + (ay >> 1)) & 1) ? 0x3a : 0x30, d = (y * W + x) * 4, a = atlas.data[i + 3] / 255;
  for (let k = 0; k < 3; k++) prev.data[d + k] = edge ? 0x70 : Math.round(atlas.data[i + k] * a + bg * (1 - a));
  prev.data[d + 3] = 255;
}
mkdirSync(OUT, { recursive: true });
writeFileSync(OUT + "materials.png", PNG.sync.write(atlas));
writeFileSync(OUT + "materials-preview.png", PNG.sync.write(prev));
writeFileSync(OUT + "materials.json", JSON.stringify(meta, null, 1) + "\n");
console.log(`materials.png ${atlas.width}x${atlas.height}, ${names.length} icones`);
